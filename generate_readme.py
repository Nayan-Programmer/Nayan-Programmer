#!/usr/bin/env python3
"""Generate GitHub profile README from the local profile_config.json (no network)."""
from pathlib import Path
from urllib.parse import quote
import json,html
ROOT=Path(__file__).resolve().parent

def escape_md(s):
 return str(s).replace('|',r'\|').replace('\n',' ').strip()

def main():
 d=json.loads((ROOT/'profile_config.json').read_text('utf-8'))
 name=escape_md(d.get('name','Nayan'))
 role=escape_md(d.get('role','Founder of EchooAI'))
 git=escape_md(d.get('github','Nayan-Programmer'))
 company=escape_md(d.get('company','EchooAI'))
 pitch=escape_md(d.get('pitch','Something new is coming.'))
 git_url='https://github.com/'+quote(git)
 skills=d.get('skills',[])
 hobby=d.get('hobbies',[])
 skills_line=(' · '.join('`'+escape_md(x)+'`' for x in skills)
              if skills else '*The real stack is part of the secret mission. The icons above are editable design examples, not a verified skills list.*')
 hobby_line=(' · '.join(escape_md(x) for x in hobby))
 mail=escape_md(d.get('email',''))
 extra_contact=(f' · [Email](mailto:{quote(mail,safe="@.+-_")})' if mail else '')
 # No faux public project URLs or pretend GitHub star counters.
 projects='''| **EchooAI** | Founder-led AI venture | 🔒 Private build |
| **Classified missions** | Experiments and unpublished work | 🥷 Under wraps |
| **The next drop** | Something new is coming | ⚡ Coming soon |'''
 md=f'''<!-- Generated with generate_readme.py. Edit profile_config.json, then run python build_profile.py. -->
<div align="center">

<img src="./hero.svg?v=1" alt="{html.escape(name,quote=True)} — {html.escape(role,quote=True)} — EchooAI stealth introduction" width="100%" />

<br />

### 🥷 Hey, I'm {name}.
**{role} · @{git}**

**Private repos. Public ambition.**

*Training in silence. Building the next chapter of {company}.*

<a href="{html.escape(git_url,quote=True)}"><b>Visit my GitHub</b></a>

<br /><br />

<img src="./about-life.svg?v=1" alt="My ninja way, EchooAI mission and training arc" width="100%" />

<br /><br />

<img src="./stack.svg?v=1" alt="My illustrated jutsu tech arsenal and orbiting technology icons" width="100%" />

<br />

{skills_line}

<br /><br />

<img src="./id-dashboard.svg?v=1" alt="Nayan's ninja registration badge and classified EchooAI mission dashboard" width="100%" />

</div>

## 🍥 S-Rank Missions — Classified Scrolls

My repositories are intentionally private. The names, code, stars and details of unreleased work aren't being disclosed here.

| Mission | Focus | Status |
| :--- | :--- | :--- |
{projects}

> **My ninja way:** Train in silence. Build with purpose. Reveal at the right moment.

## ⚡ Training arc

{hobby_line if hobby_line else 'Stealth builds · AI exploration · Future ideas'}

## 🌃 Contribution Village

<div align="center">

*Every commit raises another building. This 3D night-view city is generated by a daily GitHub Action.*

<img src="./profile-3d-contrib/profile-night-view.svg?v=1" alt="Daily 3D contribution city; placeholder until the workflow completes" width="100%" />

<br /><br />

<img src="./connect.svg?v=1" alt="Connect with Nayan-Programmer and follow EchooAI's next launch" width="100%" />

<br />

<a href="{html.escape(git_url,quote=True)}"><b>GitHub: @{git}</b></a>{extra_contact}

<br /><br />

**Something new is coming.** 🍃

*The scroll is sealed. The mission continues.*

</div>

<!--
Privacy: No private repository names or source code are included.
To show private contribution counts without repository details, opt in using GitHub's contribution visibility setting.
The 3D card uses a static placeholder until .github/workflows/profile-3d.yml runs successfully.
All five animated cards contain their own images, text glyph outlines and CSS/SMIL animation, with no external asset requests.
-->
'''
 (ROOT/'README.md').write_text(md,encoding='utf-8')
 print('README.md updated for',git)
if __name__=='__main__':main()
