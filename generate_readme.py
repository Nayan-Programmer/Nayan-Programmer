#!/usr/bin/env python3
"""Generate README.md using profile_config.json; no external dependencies."""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parent

def md(s):
    return str(s).replace('|', r'\|').replace('\n', ' ').strip()

def main():
    d=json.loads((ROOT/'profile_config.json').read_text(encoding='utf-8'))
    name=md(d.get('name') or 'YOUR NAME')
    role=md(d.get('role') or 'Developer')
    git=md(d.get('github') or 'YOUR_USERNAME')
    email=md(d.get('email') or 'you@example.com')
    location=md(d.get('location') or 'Your City')
    company=md(d.get('company') or 'Your Company')
    pitch=md(d.get('pitch') or 'Building useful things with code and curiosity.')
    skills=', '.join(md(x) for x in d.get('skills', []))
    hobbies=', '.join(md(x) for x in d.get('hobbies', []))
    url=(d.get('links') or {}).get('linkedin') or 'https://www.linkedin.com/'
    projects='\n'.join(f'| [{md(p.get("name", "repository"))}](https://github.com/{git}/{md(p.get("name", "repository"))}) | {int(p.get("stars", 0))} |' for p in d.get('repos', []))
    if not projects: projects='| [Your project](https://github.com/'+git+') | 0 |'
    body=f'''<!-- Generated by generate_readme.py from profile_config.json. Re-run python build_profile.py after edits. -->
<div align="center">

![{name} — animated introduction](./hero.svg?v=1)

</div>

<div align="center">

[GitHub](https://github.com/{git}) · [LinkedIn]({url}) · [Email](mailto:{email})

</div>

## About me

**{name}** · **{role}** · {location} · {company}

{pitch}

![About and life](./about-life.svg?v=1)

## My toolkit

{skills}

![Animated tech stack](./stack.svg?v=1)

## A little more about me

{hobbies}

![Creator ID and dashboard](./id-dashboard.svg?v=1)

> The repo numbers in this illustration are entered in `profile_config.json`; they do **not** fetch live GitHub data. Replace demo values before publishing.

## Featured projects

| Repository | Stars (manual) |
|---|---:|
{projects}

## Contribution skyline

<!-- This file is generated by the scheduled workflow after its first successful run. -->
![3D contribution city — night view](./profile-3d-contrib/profile-night-view.svg?v=1)

## Connect

[![Connect with me](./connect.svg?v=1)](https://github.com/{git})

GitHub: https://github.com/{git} · Email: {email}

---

<sub>SVG cards are self-contained and contain embedded character images and vector text outlines. The 3D contribution skyline is generated separately by [yoshi389111/github-profile-3d-contrib](https://github.com/yoshi389111/github-profile-3d-contrib).</sub>
'''
    (ROOT/'README.md').write_text(body,encoding='utf-8')
    print('README.md updated')

if __name__=='__main__':main()
